#ifndef _LTCORE_DATA_SIZE_H_
#define _LTCORE_DATA_SIZE_H_

#define LTCORE_KB(n) ((n) * 1000ULL)
#define LTCORE_MB(n) ((n) * (1000ULL * 1000))
#define LTCORE_GB(n) ((n) * (1000ULL * 1000 * 1000))
#define LTCORE_TB(n) ((n) * (1000ULL * 1000 * 1000 * 1000))

#define LTCORE_KiB(n) ((n) * 1024ULL)
#define LTCORE_MiB(n) ((n) * (1024ULL * 1024))
#define LTCORE_GiB(n) ((n) * (1024ULL * 1024 * 1024))
#define LTCORE_TiB(n) ((n) * (1024ULL * 1024 * 1024 * 1024))

#endif
